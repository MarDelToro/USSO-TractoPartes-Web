begin;

-- Bitácora única de los movimientos importantes de cada ronda.
create table if not exists public.auction_events (
  id bigint generated by default as identity primary key,
  listing_id uuid not null references public.listings(id) on delete restrict,
  auction_round integer not null default 1,
  event_type text not null,
  user_id uuid references auth.users(id) on delete set null,
  payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create unique index if not exists auction_events_one_close_per_round
  on public.auction_events(listing_id, auction_round, event_type)
  where event_type = 'auction_closed';

create index if not exists auction_events_listing_created_idx
  on public.auction_events(listing_id, created_at desc);

alter table public.auction_events enable row level security;
drop policy if exists "Administradores ven eventos de subasta" on public.auction_events;
create policy "Administradores ven eventos de subasta"
  on public.auction_events for select to authenticated
  using (public.is_admin());

-- Estado de entrega para que un aviso nunca quede como una acción invisible.
alter table public.notifications add column if not exists delivery_attempts integer not null default 0;
alter table public.notifications add column if not exists last_attempt_at timestamptz;
alter table public.notifications add column if not exists delivered_at timestamptz;
alter table public.notifications add column if not exists delivery_error text;

-- Esta es la única operación que decide ganador y cierra una ronda. El bloqueo
-- evita dos cierres simultáneos y el evento único evita resultados duplicados.
create or replace function public.finalize_listing_internal(
  p_listing_id uuid,
  p_force boolean default false
)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  v_listing public.listings%rowtype;
  v_winner uuid;
  v_amount numeric;
  v_bid_count integer;
begin
  select * into v_listing
  from public.listings
  where id = p_listing_id
  for update;

  if not found then return false; end if;
  if v_listing.status = 'closed' then return false; end if;
  if v_listing.status <> 'active' then return false; end if;
  if not p_force and (v_listing.ends_at is null or v_listing.ends_at > now()) then
    return false;
  end if;

  select b.user_id, b.amount into v_winner, v_amount
  from public.bids b
  where b.listing_id = v_listing.id
    and b.auction_round = v_listing.auction_round
  order by b.amount desc, b.created_at desc
  limit 1;

  select count(*) into v_bid_count
  from public.bids b
  where b.listing_id = v_listing.id
    and b.auction_round = v_listing.auction_round;

  update public.listings
  set status = 'closed',
      winner_id = v_winner,
      current_price = coalesce(v_amount, current_price, start_price),
      ends_at = case when p_force then least(coalesce(ends_at, now()), now()) else ends_at end
  where id = v_listing.id;

  insert into public.auction_events(listing_id, auction_round, event_type, user_id, payload)
  values (
    v_listing.id,
    v_listing.auction_round,
    'auction_closed',
    v_winner,
    jsonb_build_object(
      'final_price', coalesce(v_amount, v_listing.current_price, v_listing.start_price),
      'title', v_listing.title,
      'bid_count', v_bid_count,
      'forced', p_force
    )
  )
  on conflict (listing_id, auction_round, event_type)
    where event_type = 'auction_closed' do nothing;

  return true;
end;
$$;

-- El historial financiero y de rondas nunca se elimina por accidente.
create or replace function public.protect_listing_history()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if exists (select 1 from public.bids where listing_id = old.id)
     or exists (select 1 from public.auction_events where listing_id = old.id) then
    raise exception 'Este lote ya tiene historial. Consérvalo o márcalo como cerrado; no puede eliminarse.';
  end if;
  return old;
end;
$$;

drop trigger if exists protect_listing_history_before_delete on public.listings;
create trigger protect_listing_history_before_delete
before delete on public.listings
for each row execute function public.protect_listing_history();

create or replace function public.record_listing_reopen()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if new.auction_round > old.auction_round then
    insert into public.auction_events(listing_id, auction_round, event_type, payload)
    values (new.id, new.auction_round, 'auction_reopened',
      jsonb_build_object('previous_round', old.auction_round, 'title', new.title));
  end if;
  return new;
end;
$$;

drop trigger if exists record_listing_reopen_after_update on public.listings;
create trigger record_listing_reopen_after_update
after update of auction_round on public.listings
for each row execute function public.record_listing_reopen();

create or replace function public.close_listing(p_listing_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.is_admin() then
    raise exception 'Solo un administrador puede cerrar subastas';
  end if;
  perform public.finalize_listing_internal(p_listing_id, true);
end;
$$;

create or replace function public.expire_listings()
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_id uuid;
begin
  for v_id in
    select id from public.listings
    where status = 'active' and ends_at is not null and ends_at <= now()
    order by ends_at
  loop
    perform public.finalize_listing_internal(v_id, false);
  end loop;
end;
$$;

-- Una llamada coordina los trabajos periódicos. Cada tarea sigue siendo
-- idempotente, así que puede repetirse sin producir cierres o avisos dobles.
create or replace function public.run_auction_operations()
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  perform public.expire_listings();
  if to_regprocedure('public.dispatch_upcoming_auction_reminders()') is not null then
    -- Un fallo al preparar recordatorios nunca debe impedir que una subasta
    -- vencida se cierre. El cierre seguro siempre se ejecuta primero.
    begin
      perform public.dispatch_upcoming_auction_reminders();
    exception when others then
      raise warning 'No se pudieron preparar recordatorios de próximas subastas: %', sqlerrm;
    end;
  end if;
end;
$$;

-- El administrador registra cada intento de contacto desde una sola función.
create or replace function public.admin_mark_notification_delivery(
  p_notification_id text,
  p_success boolean,
  p_error text default null
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.is_admin() then
    raise exception 'Solo un administrador puede registrar avisos';
  end if;

  update public.notifications n
  set status = case when p_success then 'sent' else 'pending' end,
      delivery_attempts = coalesce(n.delivery_attempts, 0) + 1,
      last_attempt_at = now(),
      delivered_at = case when p_success then now() else n.delivered_at end,
      delivery_error = case when p_success then null else nullif(p_error, '') end
  where n.id::text = p_notification_id;
end;
$$;

-- Resumen pequeño para detectar problemas sin revisar tablas técnicas.
create or replace function public.admin_operations_health()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_result jsonb;
  v_scheduler_available boolean := false;
  v_scheduler_configured boolean := false;
begin
  if not public.is_admin() then
    raise exception 'Solo un administrador puede consultar el estado del sistema';
  end if;

  select exists(select 1 from pg_extension where extname = 'pg_cron')
    into v_scheduler_available;

  if v_scheduler_available then
    begin
      execute 'select exists (select 1 from cron.job where jobname = $1)'
        into v_scheduler_configured
        using 'usso-auction-operations';
    exception when others then
      v_scheduler_configured := false;
    end;
  end if;

  select jsonb_build_object(
    'checked_at', now(),
    'expired_active_listings', (select count(*) from public.listings where status = 'active' and ends_at <= now()),
    'pending_notifications', (select count(*) from public.notifications where coalesce(status, 'pending') <> 'sent'),
    'stale_notifications', (select count(*) from public.notifications where coalesce(status, 'pending') <> 'sent' and created_at < now() - interval '15 minutes'),
    'failed_notifications', (select count(*) from public.notifications where delivery_error is not null),
    'incomplete_closed_listings', (
      select count(*)
      from public.listings l
      where l.status = 'closed'
        and exists (
          select 1
          from public.bids b
          where b.listing_id = l.id
            and b.auction_round = l.auction_round
        )
        and l.winner_id is distinct from (
          select b.user_id
          from public.bids b
          where b.listing_id = l.id
            and b.auction_round = l.auction_round
          order by b.amount desc, b.created_at desc
          limit 1
        )
    ),
    'missing_close_events', (
      select count(*)
      from public.listings l
      where l.status = 'closed'
        and not exists (
          select 1
          from public.auction_events e
          where e.listing_id = l.id
            and e.auction_round = l.auction_round
            and e.event_type = 'auction_closed'
        )
    ),
    'close_events', (select count(*) from public.auction_events where event_type = 'auction_closed'),
    'scheduler_available', v_scheduler_available,
    'scheduler_configured', v_scheduler_configured
  ) into v_result;

  return v_result;
end;
$$;

-- Conserva una bitácora de las rondas ya cerradas antes de esta mejora.
insert into public.auction_events(listing_id, auction_round, event_type, user_id, payload, created_at)
select l.id, l.auction_round, 'auction_closed', l.winner_id,
       jsonb_build_object('final_price', coalesce(l.current_price, l.start_price), 'backfilled', true),
       coalesce(l.ends_at, l.created_at, now())
from public.listings l
where l.status = 'closed'
on conflict (listing_id, auction_round, event_type)
  where event_type = 'auction_closed' do nothing;

revoke all on function public.finalize_listing_internal(uuid, boolean) from public, anon, authenticated;
revoke all on function public.close_listing(uuid) from public, anon;
revoke all on function public.expire_listings() from public;
revoke all on function public.run_auction_operations() from public;
revoke all on function public.admin_mark_notification_delivery(text, boolean, text) from public, anon;
revoke all on function public.admin_operations_health() from public, anon;
grant execute on function public.close_listing(uuid) to authenticated;
-- Mantiene compatibilidad con las vistas ya publicadas: esta función solo
-- puede cerrar lotes cuyo reloj ya llegó a cero.
grant execute on function public.expire_listings() to anon, authenticated;
grant execute on function public.run_auction_operations() to authenticated;
grant execute on function public.admin_mark_notification_delivery(text, boolean, text) to authenticated;
grant execute on function public.admin_operations_health() to authenticated;
grant select on public.auction_events to authenticated;

-- Un minuto ofrece cierres puntuales aun cuando nadie tenga abierta la web.
do $$
begin
  if exists (select 1 from pg_extension where extname = 'pg_cron') then
    execute $cron$
      select cron.schedule(
        'usso-auction-operations', '* * * * *',
        'select public.run_auction_operations()'
      )
      where not exists (
        select 1 from cron.job where jobname = 'usso-auction-operations'
      )
    $cron$;
  end if;
end;
$$;

commit;
